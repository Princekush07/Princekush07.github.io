export function flattenDays(weeks) {
  return weeks.flatMap((w, wi) =>
    w.days.map((d, di) => ({
      ...d,
      weekId: w.id,
      weekIndex: wi,
      dayIndex: di,
      globalIndex:
        weeks.slice(0, wi).reduce((acc, w2) => acc + w2.days.length, 0) + di,
    })),
  );
}
